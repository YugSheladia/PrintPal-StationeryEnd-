using System;
using System.Diagnostics;
using System.IO;
using System.Text;
using System.Threading.Tasks;
using UnityEngine;





public static class PrintHeaderGenerator
{

    public static Task<string> GenerateAsync
    (
        int UserID,
        string UserName,
        int OrderID,
        int PrintID,
        string PDFName
    )
    {
        // Access Unity API on the main thread.
        string PersistentDataPath = Application.persistentDataPath;

        return Task.Run(() =>
        {
            string FolderPath = Path.Combine(
                PersistentDataPath,
                "PrintHeaders"
            );

            Directory.CreateDirectory(FolderPath);

            string BaseName = $"Header_Order{OrderID}_Print{PrintID}";
            string HTMLPath = Path.Combine(FolderPath, BaseName + ".html");
            string PDFPath = Path.Combine(FolderPath, BaseName + ".pdf");

            string SafeUserName = System.Net.WebUtility.HtmlEncode(
                UserName ?? "Unknown"
            );

            string SafePDFName = System.Net.WebUtility.HtmlEncode(
                PDFName ?? "Unknown document"
            );

            string HTML = $@"<!DOCTYPE html>
                                <html>
                                <head>
                                <meta charset=""utf-8"">
                                <style>
                                    @page {{ size: A4; margin: 18mm; }}
                                    body {{ font-family: Arial, sans-serif; color: #111; font-size: 16px; }}
                                    .header {{ border: 2px solid #222; padding: 24px; }}
                                    h1 {{ font-size: 26px; margin-top: 0; border-bottom: 1px solid #999; padding-bottom: 12px; }}
                                    .field {{ margin: 16px 0; }}
                                    .label {{ font-weight: bold; }}
                                    .footer {{ margin-top: 28px; font-size: 12px; color: #555; }}
                                </style>
                                </head>
                                <body>
                                    <div class=""header"">
                                        <h1>PrintPal — Document Header</h1>
                                        <div class=""field""><span class=""label"">Customer:</span> {SafeUserName}</div>
                                        <div class=""field""><span class=""label"">User ID:</span> {UserID}</div>
                                        <div class=""field""><span class=""label"">Order ID:</span> {OrderID}</div>
                                        <div class=""field""><span class=""label"">Print ID:</span> {PrintID}</div>
                                        <div class=""field""><span class=""label"">Document:</span> {SafePDFName}</div>
                                        <div class=""footer"">Generated by PrintPal</div>
                                    </div>
                                </body>
                                </html>";

            File.WriteAllText(HTMLPath, HTML, Encoding.UTF8);

            string EdgePath = FindEdgePath();

            if (string.IsNullOrEmpty(EdgePath))
            {
                throw new FileNotFoundException(
                    "Microsoft Edge was not found. " +
                    "Install Edge or configure its executable path."
                );
            }

            string ProfilePath = Path.Combine(
                FolderPath,
                "EdgeProfile_" + PrintID
            );

            string Arguments =
                "--headless " +
                "--disable-gpu " +
                "--no-first-run " +
                "--no-pdf-header-footer " +
                $"--user-data-dir=\"{ProfilePath}\" " +
                $"--print-to-pdf=\"{PDFPath}\" " +
                $"\"{new Uri(HTMLPath).AbsoluteUri}\"";

            using (Process Process = new Process())
            {
                Process.StartInfo.FileName = EdgePath;
                Process.StartInfo.Arguments = Arguments;
                Process.StartInfo.UseShellExecute = false;
                Process.StartInfo.CreateNoWindow = true;
                Process.StartInfo.WindowStyle = ProcessWindowStyle.Hidden;

                Process.Start();

                if (!Process.WaitForExit(30000))
                {
                    try { Process.Kill(); } catch { }

                    throw new TimeoutException(
                        "Edge took too long to generate the header PDF."
                    );
                }

                if (!File.Exists(PDFPath) ||
                    new FileInfo(PDFPath).Length == 0)
                {
                    throw new Exception(
                        "Edge finished, but the header PDF was not created."
                    );
                }
            }

            return PDFPath;
        });
    }







    private static string FindEdgePath()
    {
        string[] Paths =
        {
            Path.Combine(
                Environment.GetFolderPath(
                    Environment.SpecialFolder.ProgramFilesX86),
                "Microsoft", "Edge", "Application", "msedge.exe"
            ),

            Path.Combine(
                Environment.GetFolderPath(
                    Environment.SpecialFolder.ProgramFiles),
                "Microsoft", "Edge", "Application", "msedge.exe"
            )
        };

        foreach (string PathToCheck in Paths)
        {
            if (File.Exists(PathToCheck))
                return PathToCheck;
        }

        return null;
    }
}
